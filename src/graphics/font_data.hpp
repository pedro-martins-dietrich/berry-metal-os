	// Fetches the character data and width
	inline const uint8_t* get_character_data(char character, uint16_t& width)
	{
		const size_t ascii_code = static_cast<uint8_t>(character);
		if(ascii_code < FIRST_CHAR || ascii_code > LAST_CHAR)
		{
			width = 0;
			return nullptr;
		}
		const size_t index = ascii_code - FIRST_CHAR;
		width = offsets[index + 1] - offsets[index];
		return pixels + offsets[index];
	}
